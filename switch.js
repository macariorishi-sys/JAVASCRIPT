var grade="C"
switch(grade){
    case "A":
        console.log("Excellent!");
        break;
    case "B":
        console.log("Very good!");
        break;
    case "C":
        console.log("Good.");
        break;
    case "D":
        console.log("You need to improve."); 
        break;
    case "F":
        console.log("You failed.");
        break;       
    default:
        console.log("Invalid grade.");
}